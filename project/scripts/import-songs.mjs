// Usage: node scripts/import-songs.mjs <extracted-xlsx-dir> [output.sql]
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = process.argv[2];
if (!dir) throw new Error('Pass the folder of the extracted .xlsx file.');
const read = (p) => readFileSync(join(dir, p), 'utf8');
const decode = (s) => s.replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&apos;/g, "'").replace(/&amp;/g, '&');

const shared = [...read('xl/sharedStrings.xml').matchAll(/<si>([\s\S]*?)<\/si>/g)]
  .map((m) => decode([...m[1].matchAll(/<t[^>]*>([\s\S]*?)<\/t>/g)].map((t) => t[1]).join('')));
const sheet = read('xl/worksheets/sheet1.xml');
const rels = new Map([...read('xl/worksheets/_rels/sheet1.xml.rels').matchAll(/Id="([^"]+)"[^>]*Target="([^"]+)"/g)].map((m) => [m[1], decode(m[2])]));
const links = new Map([...sheet.matchAll(/<hyperlink r:id="([^"]+)" ref="([^"]+)"/g)].map((m) => [m[2], rels.get(m[1])]));

const cells = new Map();
for (const m of sheet.matchAll(/<c r="([A-Z]+\d+)"([^>]*?)(?:\/>|>([\s\S]*?)<\/c>)/g)) {
  const v = m[3]?.match(/<v>([\s\S]*?)<\/v>/)?.[1];
  if (v === undefined) continue;
  cells.set(m[1], /t="s"/.test(m[2]) ? shared[Number(v)] : decode(v));
}

const text = (ref) => (cells.get(ref) ?? '').trim();
const url = (ref) => {
  const value = links.get(ref) ?? text(ref);
  return /^https:\/\//.test(value) ? value : '';
};
const q = (s) => `'${s.replace(/'/g, "''")}'`;
const instruments = [['E', 'Sax Alto'], ['F', 'Trompete'], ['G', 'Trombone'], ['H', 'Sax Tenor']];

const maxRow = Math.max(...[...cells.keys()].map((k) => Number(k.replace(/\D/g, ''))));
let rhythm = '';
const out = ['-- Generated by scripts/import-songs.mjs. Safe to rerun.', 'begin;', ''];
let order = 0;
for (let row = 4; row <= maxRow; row += 1) {
  const title = text(`B${row}`);
  if (!title) continue;
  if (text(`A${row}`)) rhythm = text(`A${row}`).replace(/\s+/g, ' ');
  order += 1;
  const parts = instruments.map(([col, name]) => [name, url(`${col}${row}`)]).filter(([, u]) => u);
  out.push(`with s as (
  insert into public.songs (band_id, sort_order, rhythm, title, artist, key_c, key_eb, video_url, audio_url)
  select id, ${order}, ${q(rhythm)}, ${q(title)}, ${q(text(`C${row}`))}, ${q(text(`I${row}`))}, ${q(text(`J${row}`))}, ${q(url(`L${row}`))}, ${q(url(`N${row}`))}
  from public.bands where slug = 'sardinhas-nomades'
  on conflict (band_id, title) do update set sort_order = excluded.sort_order, rhythm = excluded.rhythm, artist = excluded.artist,
    key_c = excluded.key_c, key_eb = excluded.key_eb, video_url = excluded.video_url, audio_url = excluded.audio_url
  returning id
)`);
  out.push(parts.length
    ? `insert into public.song_parts (song_id, instrument, url) select id, p.instrument, p.url from s, (values ${parts.map(([i, u]) => `(${q(i)}, ${q(u)})`).join(', ')}) as p(instrument, url)
on conflict (song_id, instrument) do update set url = excluded.url;\n`
    : 'select 1;\n');
}
out.push('commit;');
writeFileSync(process.argv[3] ?? 'supabase/seed-songs.sql', `${out.join('\n')}\n`, 'utf8');

